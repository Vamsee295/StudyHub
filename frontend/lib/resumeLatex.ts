export function resumeToLatex(doc: ResumeDoc): string {
  const out: string[] = [PREAMBLE, "\\begin{document}", ""];
  out.push("\\begin{center}");
  out.push(`    \\textbf{\\Huge \\scshape ${tex(doc.name)}} \\\\ \\vspace{1pt}`);
  if (doc.contacts.length) out.push(`    \\small ${doc.contacts.map(contact).join(" $|$ ")}`);
  out.push("\\end{center}", "");
  if (doc.summary) out.push(`\\small ${tex(doc.summary)}`, "");

  for (const s of doc.sections) {
    out.push(`\\section{${tex(s.title)}}`);
    if (s.entries?.length) {
      out.push("  \\resumeSubHeadingListStart");
      for (const e of s.entries) {
        if (e.subtitle) {
          out.push(`    \\resumeSubheading{${tex(e.title)}}{${tex(e.date ?? "")}}{${tex(e.subtitle)}}{}`);
        } else {
          // no second line: a one-line heading avoids an empty row under the title
          out.push(`    \\resumeProjectHeading{\\textbf{${tex(e.title)}}}{${tex(e.date ?? "")}}`);
        }
        if (e.bullets.length) {
          out.push("      \\resumeItemListStart");
          for (const b of e.bullets) out.push(`        \\resumeItem{${tex(b)}}`);
          out.push("      \\resumeItemListEnd");
        }
      }
      out.push("  \\resumeSubHeadingListEnd", "");
    }
    if (s.lines?.length) {
      out.push(" \\begin{itemize}[leftmargin=0.15in, label={}]", "    \\small{\\item{");
      out.push(s.lines.map((l) => `     ${l.label ? `\\textbf{${tex(l.label)}}{: ` : "{"}${tex(l.text)}}`).join(" \\\\\n"));
      out.push("    }}", " \\end{itemize}", "");
    }
  }
  out.push("\\end{document}", "");
  return out.join("\n");
}
