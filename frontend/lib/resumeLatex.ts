import type { ResumeDoc } from "@/lib/resume";

/** Escape the characters LaTeX treats specially. */
export function tex(s: string): string {
  return s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}")
    .replace(/[\u2010\u2011\u2012]/g, "-") // AI text often uses Unicode hyphens pdflatex can't typeset
    .replace(/[\u00a0\u202f\u2009]/g, " ")
    .replace(/–|—/g, "--")
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/\s*·\s*/g, " $\\cdot$ "); // pdflatex has no glyph for the middle dot
}

/** Contact items that look like links become clickable. */
function contact(item: string): string {
  const t = tex(item);
  if (/^[^@\s]+@[^@\s]+\.[a-z]{2,}$/i.test(item)) return `\\href{mailto:${item}}{\\underline{${t}}}`;
  if (/^(https?:\/\/)?([\w-]+\.)+[a-z]{2,}(\/\S*)?$/i.test(item)) {
    const url = item.startsWith("http") ? item : `https://${item}`;
    return `\\href{${url.replace(/([%#])/g, "\\$1")}}{\\underline{${t}}}`;
  }
  return t;
}

